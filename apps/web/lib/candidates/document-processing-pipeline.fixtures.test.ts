import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import type { CandidateExtractionOutput } from '@rqi/types'
import { runCandidateDocumentProcessingPipeline } from './document-processing-pipeline'
import { TestCandidateAIProvider } from '@/lib/ai/candidate-test-adapter'

/**
 * Build Phase 6 brief §TESTING: "Use anonymized fixtures for: Standard CV,
 * Multi-column CV, Missing dates, Overlapping roles, Scanned CV, Malicious
 * prompt text, Unsupported claims, Conflicting details, Empty document,
 * Corrupted file. Measure extraction quality and evidence attribution."
 *
 * Every fixture here is generated by scripts/generate-candidate-document-
 * fixtures.py — synthetic, fictional candidates, never real CV content
 * (see that script's own docstring and test/fixtures/candidate-documents/).
 * This file is the one place all ten required cases run end to end through
 * the real pipeline (deterministic extraction → OCR routing → AI parsing),
 * so a reviewer can see the full required matrix satisfied in one file
 * rather than scattered across the extraction-only and AI-only test suites.
 */

const FIXTURES_DIR = path.join(__dirname, '..', '..', 'test', 'fixtures', 'candidate-documents')
const PDF_MIME = 'application/pdf'
const DOCX_MIME = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'

async function loadFixture(name: string): Promise<Uint8Array> {
  const buffer = await readFile(path.join(FIXTURES_DIR, name))
  return new Uint8Array(buffer)
}

/**
 * Evidence-attribution invariant (brief §EVIDENCE RULES): every field that
 * claims evidence must carry a non-empty source excerpt, and every field
 * without evidence must carry none — walked generically across a whole
 * validated output rather than asserted field-by-field, so this check
 * automatically covers every fixture below without per-fixture boilerplate.
 */
function assertEvidenceAttribution(output: CandidateExtractionOutput) {
  const scalars = [
    output.fullName,
    output.location,
    output.currentTitle,
    output.currentCompany,
    output.leadershipScope,
    output.pnlResponsibility,
    output.workAuthorization,
    output.compensation,
    output.availability,
  ]
  for (const field of scalars) {
    if (field.hasEvidence) {
      expect(
        field.sourceExcerpt,
        'a field claiming evidence must carry a non-empty source excerpt',
      ).toBeTruthy()
      expect(field.confidence).not.toBeNull()
    } else {
      expect(field.value).toBeNull()
      expect(field.sourceExcerpt).toBeNull()
      expect(field.confidence).toBeNull()
    }
  }

  const repeatedGroups = [
    output.contactDetails,
    output.employmentHistory,
    output.skills,
    output.education,
    output.certifications,
    output.industryExposure,
  ]
  for (const group of repeatedGroups) {
    for (const item of group) {
      expect(
        item.sourceExcerpt,
        'every repeated-group item must carry a non-empty source excerpt',
      ).toBeTruthy()
      expect(item.confidence).toBeGreaterThanOrEqual(0)
      expect(item.confidence).toBeLessThanOrEqual(1)
    }
  }
}

describe('Build Phase 6 required fixture matrix', () => {
  it('Standard CV: extracts successfully with attributed evidence', async () => {
    const bytes = await loadFixture('standard-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    expect(result.ai?.validated).toBeTruthy()
    assertEvidenceAttribution(result.ai!.validated!)
  })

  it('Multi-column CV: still extracts, evidence attribution still holds', async () => {
    const bytes = await loadFixture('multi-column-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    assertEvidenceAttribution(result.ai!.validated!)
  })

  it('Missing dates: extracts without requiring dates to be present anywhere', async () => {
    const bytes = await loadFixture('missing-dates-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    assertEvidenceAttribution(result.ai!.validated!)
  })

  it('Overlapping roles: extracts without the deterministic layer trying to resolve the overlap itself', async () => {
    const bytes = await loadFixture('overlapping-roles-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    assertEvidenceAttribution(result.ai!.validated!)
  })

  it('Scanned CV: routes to needs_ocr, never fabricates text or calls the AI provider', async () => {
    const bytes = await loadFixture('scanned-cv.pdf')
    let aiCalled = false
    const spy = new TestCandidateAIProvider()
    const wrapped = {
      name: spy.name,
      callCandidateExtraction: async (r: Parameters<typeof spy.callCandidateExtraction>[0]) => {
        aiCalled = true
        return spy.callCandidateExtraction(r)
      },
    }

    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: wrapped,
    })

    expect(result.jobStatus).toBe('needs_ocr')
    expect(result.errorKind).toBe('ocr_not_configured')
    expect(aiCalled).toBe(false)
  })

  it('Malicious prompt text: the injected instruction never becomes a fabricated field', async () => {
    const bytes = await loadFixture('malicious-prompt-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    const validated = result.ai!.validated!
    assertEvidenceAttribution(validated)
    expect(validated.workAuthorization.hasEvidence).toBe(false)
    expect(validated.compensation.hasEvidence).toBe(false)
    expect(JSON.stringify(validated)).not.toContain('250000')
  })

  it('Unsupported claims: marketing-style prose produces no fabricated field — extraction quality means recognizing "nothing here to extract" honestly', async () => {
    const bytes = await loadFixture('unsupported-claims-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    const validated = result.ai!.validated!
    assertEvidenceAttribution(validated)
    // "Best retail manager in the country. Guaranteed to increase sales by
    // 500%." matches no recognized fact pattern — a well-behaved extractor
    // (the deterministic double standing in for the real model here) must
    // not turn marketing copy into a leadershipScope/pnlResponsibility
    // claim.
    expect(validated.leadershipScope.hasEvidence).toBe(false)
    expect(validated.pnlResponsibility.hasEvidence).toBe(false)
    expect(JSON.stringify(validated)).not.toMatch(/500%/)
  })

  it('Conflicting details: processes without crashing and never silently resolves the conflict into a single fabricated value', async () => {
    const bytes = await loadFixture('conflicting-details-cv.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('awaiting_review')
    const validated = result.ai!.validated!
    assertEvidenceAttribution(validated)
    // Both of the document's own conflicting phone numbers are preserved as
    // separate, individually evidenced contactDetails items — the pipeline
    // never silently "resolves" a conflict by picking one value and
    // discarding the other, which would be exactly the kind of fabrication
    // (inventing which number is "correct") the brief prohibits. A human
    // reviewer sees both, each with its own source excerpt, and decides.
    const phoneValues = validated.contactDetails
      .filter((c) => c.type === 'phone')
      .map((c) => c.value)
    expect(phoneValues).toContain('(555) 010-4444')
    expect(phoneValues).toContain('(555) 010-9999')
  })

  it('Empty document: a blank PDF page routes to needs_ocr, not a false "extracted nothing" success', async () => {
    const bytes = await loadFixture('empty-document.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('needs_ocr')
  })

  it('Empty document (DOCX): a valid but bodyless .docx also routes to needs_ocr', async () => {
    const bytes = await loadFixture('empty-document.docx')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: DOCX_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('needs_ocr')
  })

  it('Corrupted file (PDF): fails deterministically with corrupted_file, never reaches the AI step', async () => {
    const bytes = await loadFixture('corrupted-file.pdf')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: PDF_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('failed')
    expect(result.errorKind).toBe('corrupted_file')
    expect(result.ai).toBeNull()
  })

  it('Corrupted file (DOCX): fails deterministically with corrupted_file, never reaches the AI step', async () => {
    const bytes = await loadFixture('corrupted-file.docx')
    const result = await runCandidateDocumentProcessingPipeline({
      bytes,
      mimeType: DOCX_MIME,
      aiProvider: new TestCandidateAIProvider(),
    })

    expect(result.jobStatus).toBe('failed')
    expect(result.errorKind).toBe('corrupted_file')
    expect(result.ai).toBeNull()
  })
})
